function runCommand(command, cwd, timeoutMs, env) {
  return new Promise((resolvePromise) => {
    let out = ''
    let err = ''
    let settled = false
    let child
    try {
      // shell:true 让 Node 在 Windows 上用 cmd.exe /d /s /c "…" 正确转义整条命令；
      // 手工拼 cmd.exe 参数会把命令当字符串丢掉（实测 Copy-Item 不会执行）。
      child = spawn(String(command), {
        shell: true,
        cwd: cwd && isDir(cwd) ? cwd : undefined,
        env: { ...process.env, PYTHONUNBUFFERED: '1', PYTHONIOENCODING: 'utf-8', ...(env || {}) },
        windowsHide: true,
      })
    } catch (e) {
      resolvePromise({ ok: false, code: -1, out: '', err: String(e?.message || e) })
      return
    }
    const finish = (result) => {
      if (settled) return
      settled = true
      resolvePromise(result)
    }
    const timer = setTimeout(() => {
      try {
        child.kill()
      } catch {
        /* ignore */
      }
      finish({ ok: false, code: -2, out, err: `${err}\n[超时 ${timeoutMs}ms]` })
    }, timeoutMs)
    child.stdout?.on('data', (c) => {
      out = (out + c.toString('utf8')).slice(-200_000)
    })
    child.stderr?.on('data', (c) => {
      err = (err + c.toString('utf8')).slice(-200_000)
    })
    child.on('error', (e) => {
      clearTimeout(timer)
      finish({ ok: false, code: -1, out, err: `${err}\n${String(e?.message || e)}` })
    })
    child.on('close', (code) => {
      clearTimeout(timer)
      finish({ ok: code === 0, code, out, err })
    })
  })
}

