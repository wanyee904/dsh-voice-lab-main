function wavDuration(buf) {
  try {
    if (buf.length < 44 || buf.toString('ascii', 0, 4) !== 'RIFF') return null
    let offset = 12
    let sampleRate = 0
    let channels = 0
    let bits = 16
    let dataSize = 0
    while (offset + 8 <= buf.length) {
      const id = buf.toString('ascii', offset, offset + 4)
      const size = buf.readUInt32LE(offset + 4)
      const body = offset + 8
      if (id === 'fmt ') {
        channels = buf.readUInt16LE(body + 2)
        sampleRate = buf.readUInt32LE(body + 4)
        bits = buf.readUInt16LE(body + 14) || 16
      } else if (id === 'data') {
        dataSize = Math.min(size, buf.length - body)
        break
      }
      offset = body + size + (size % 2)
    }
    if (!sampleRate || !channels || !dataSize) return null
    return dataSize / (sampleRate * channels * (bits / 8))
  } catch {
    return null
  }
}

function isWavFile(file) {
  try {
    const fd = openSync(file, 'r')
    try {
      const head = Buffer.alloc(12)
      const read = readSync(fd, head, 0, 12, 0)
      if (read < 12) return false
      const riff = head.toString('ascii', 0, 4)
      const wave = head.toString('ascii', 8, 12)
      return (riff === 'RIFF' || riff === 'RF64') && wave === 'WAVE'
    } finally {
      closeSync(fd)
    }
  } catch {
    return false
  }
}

