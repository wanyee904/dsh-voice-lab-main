function sanitizeUi(ui) {
  const raw = ui && typeof ui === 'object' ? ui : {}
  const map = {}
  if (raw.readEngineByPreset && typeof raw.readEngineByPreset === 'object') {
    for (const [id, engine] of Object.entries(raw.readEngineByPreset)) {
      if (!/^[a-z0-9:_-]{3,80}$/i.test(String(id))) continue
      if (!UI_ENGINES.includes(engine)) continue
      map[id] = engine
      if (Object.keys(map).length >= 200) break
    }
  }
  return {
    tab: UI_TABS.includes(raw.tab) ? raw.tab : 'studio',
    selectedPresetId: String(raw.selectedPresetId || '').slice(0, 80),
    line: String(raw.line || '').slice(0, 2000),
    readEngine: UI_ENGINES.includes(raw.readEngine) ? raw.readEngine : 'auto',
    readEngineByPreset: map,
    preferNew: raw.preferNew !== false,
    autoRead: typeof raw.autoRead === 'boolean' ? raw.autoRead : null,
    autoPlay: typeof raw.autoPlay === 'boolean' ? raw.autoPlay : null,
  }
}

